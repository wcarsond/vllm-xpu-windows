# gen-moe-split.input.py - write the per-variant translation units for the Xe2 MoE grouped GEMM, one or two kernels each.
# Usage:  .venv312\Scripts\python.exe kernels\gen-moe-split.input.py      (writes into src\vllm-xpu-kernels\csrc\xpu\grouped_gemm\xe_2\)
# Why (2026-10-11): grouped_gemm_xe2_interface.hpp instantiated ~62 cutlass GEMM kernels in a single translation unit, and that
# one compile needed over 30 GB on this 32 GB PC (attempt 11, MoE has been off since). The attention kernels avoid the same
# problem with one file per variant. This generates: grouped_gemm_xe2_launch.hpp (argument struct, family enum, 36 launcher
# declarations, select_launcher), split/select.cpp (the table), and split/launch_<family>_<policy>_<adtype>.cpp (36 files,
# each instantiating one family template for one tile policy and one activation type: 1-2 kernels). The heavy code lives in
# grouped_gemm_xe2_families.hpp, included only by the 36 small files. add_xe2_kernel_library globs *.cpp recursively.
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1] / "src" / "vllm-xpu-kernels" / "csrc" / "xpu" / "grouped_gemm" / "xe_2"
SPLIT = ROOT / "split"
SPLIT.mkdir(exist_ok=True)

# family -> (dispatch enum, ordered tile policies as (short name, policy class), template call shape)
FAMILIES = {
    "w4a16":    ("W4A16",     [("m8", "w4a16_policy_m_8"), ("m16", "w4a16_policy_m_16"), ("m32", "w4a16_policy_m_32"), ("full", "w4a16_policy")],
                 "w4a16_launch<{policy}, {scalar}>(a);"),
    "mxfp8":    ("MXFP8",     [("m16", "w8a16_policy_m_16"), ("m32", "w8a16_policy_m_32"), ("full", "w8a16_policy")],
                 "fp8_launch<{policy}, {scalar}, B_DTYPE::MXFP8, uint8_t>(a);"),
    "blockfp8": ("BLOCK_FP8", [("m16", "w8a16_policy_m_16"), ("m32", "w8a16_policy_m_32"), ("full", "w8a16_policy")],
                 "fp8_launch<{policy}, {scalar}, B_DTYPE::BLOCK_FP8, float>(a);"),
    "fp8":      ("FP8",       [("m16", "w8a16_policy_m_16"), ("m32", "w8a16_policy_m_32"), ("full", "w8a16_policy")],
                 "fp8_launch<{policy}, {scalar}, B_DTYPE::PER_TENSOR_FP8, float>(a);"),
    "w16a16":   ("W16A16",    [("m16", "w16a16_policy_m_16"), ("m32", "w16a16_policy_m_32"), ("n64", "w16a16_policy_n_64"),
                               ("n128", "w16a16_policy_n_128"), ("full", "w16a16_policy")],
                 "w16a16_launch<{policy}, {scalar}>(a);"),
}
ADTYPES = [("half", "half_t"), ("bf16", "bfloat16_t")]   # index 0 = half, 1 = bf16 (select_launcher indexes by a_bf16)
HEAD = "// Generated by scripts/vllm-xpu-windows/kernels/gen-moe-split.input.py - edit the generator, not this file.\n"

decls, files, table = [], [], []
for fam, (enum, policies, call) in FAMILIES.items():
    rows = []
    for pname, pclass in policies:
        cells = []
        for aname, scalar in ADTYPES:
            fn = f"launch_{fam}_{pname}_{aname}"
            decls.append(f"void {fn}(const MoELaunchArgs& a);")
            body = call.format(policy=pclass, scalar=scalar)
            (SPLIT / f"{fn}.cpp").write_text(
                HEAD + "// One MoE grouped-GEMM variant per translation unit so a 32 GB machine can compile it.\n"
                '#include "../grouped_gemm_xe2_families.hpp"\n\nnamespace MoE {\n'
                f"void {fn}(const MoELaunchArgs& a) {{ {body} }}\n}}  // namespace MoE\n", encoding="utf-8")
            files.append(fn)
            cells.append(fn)
        rows.append("{" + ", ".join(cells) + "}")
    table.append((enum, len(policies), rows))

launch_hpp = HEAD + """#pragma once
// Light interface between the MoE grouped-GEMM dispatch (grouped_gemm_xe2_interface.hpp, no cutlass includes) and the
// per-variant translation units in split/ (each includes grouped_gemm_xe2_families.hpp, the heavy part).
#include <cstdint>
#include <sycl/sycl.hpp>
#include <c10/core/ScalarType.h>

namespace MoE {

struct MoELaunchArgs {
  sycl::queue* queue;
  const void* A;              // activations [Total_M, K]
  const void* B;              // weights, layout per family
  const void* scales;         // nullptr when the family has none
  const void* bias;           // nullptr when absent, else [num_experts, N] in the activation type
  void* D;                    // outputs [Total_M, N] in the activation type
  int N;
  int K;
  const int* rows_per_expert;
  int num_experts;
  int group_size;
  int32_t* atomic_buffer;     // zeroed [1] int32 work counter
  c10::ScalarType A_dtype;
  c10::ScalarType B_dtype;
  bool is_int4;               // w4a16 family only: int4 weights (else mxfp4)
  bool is_mxfp4;
};

enum class MoEFamily { W4A16, MXFP8, BLOCK_FP8, FP8, W16A16 };

using MoELaunchFn = void (*)(const MoELaunchArgs&);

// policy index: W4A16 {m8, m16, m32, full}; MXFP8/BLOCK_FP8/FP8 {m16, m32, full}; W16A16 {m16, m32, n64, n128, full}
MoELaunchFn select_launcher(MoEFamily family, int policy, bool a_bf16);

""" + "\n".join(decls) + "\n\n}  // namespace MoE\n"
(ROOT / "grouped_gemm_xe2_launch.hpp").write_text(launch_hpp, encoding="utf-8")

select_cpp = HEAD + '#include <c10/util/Exception.h>\n#include "../grouped_gemm_xe2_launch.hpp"\n\nnamespace MoE {\n\n' \
    "MoELaunchFn select_launcher(MoEFamily family, int policy, bool a_bf16) {\n  const int t = a_bf16 ? 1 : 0;\n  switch (family) {\n"
for enum, n, rows in table:
    select_cpp += f"    case MoEFamily::{enum}: {{\n      static const MoELaunchFn table[{n}][2] = {{\n        " + ",\n        ".join(rows) + "};\n"
    select_cpp += f"      TORCH_CHECK(0 <= policy && policy < {n}, \"MoE {enum}: bad policy index \", policy);\n      return table[policy][t];\n    }}\n"
select_cpp += "  }\n  TORCH_CHECK(false, \"MoE grouped gemm: unknown family\");\n  return nullptr;\n}\n\n}  // namespace MoE\n"
(SPLIT / "select.cpp").write_text(select_cpp, encoding="utf-8")

print(f"wrote {len(files)} launcher files + select.cpp into {SPLIT}, and {ROOT / 'grouped_gemm_xe2_launch.hpp'}")
for f in files:
    print("  ", f)
